/**
 * Retorna o versículo do dia com base na data atual.
 * Usa o dia do ano (1-366) como índice, com fallback circular.
 */
export function getVersiculoDoDia(date: Date = new Date()): Versiculo {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay); // 1-366
  const index = (dayOfYear - 1) % versiculos.length;
  return versiculos[index];
}
